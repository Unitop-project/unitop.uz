export type I18nKey = keyof (typeof messages)["uz"];

export const langKeys: Record<string, I18nKey> = {
  uzbek: "lang.uzbek",
  rus: "lang.rus",
  ingliz: "lang.ingliz",
  qoraqalpoq: "lang.qoraqalpoq",
};

export const typeKeys: Record<string, I18nKey> = {
  grant: "type.grant",
  kontrakt: "type.kontrakt",
};

export const formatKeys: Record<string, I18nKey> = {
  kunduzgi: "format.kunduzgi",
  sirtqi: "format.sirtqi",
  kechki: "format.kechki",
  masofaviy: "format.masofaviy",
};

function interpolate(str: string, vars?: Record<string, string | number>) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) =>
    k in vars ? String(vars[k as keyof typeof vars]) : m,
  );
}

export interface I18nValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: I18nKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("uz");

  useEffect(() => {
    try {
      const raw = window.localStorage.getItem(STORAGE_KEY);
      if (raw === "uz" || raw === "ru" || raw === "en") setLangState(raw);
    } catch {
      /* ignore */
    }
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback(
    (key: I18nKey, vars?: Record<string, string | number>) => {
      const table = messages[lang];
      const value = key in table ? table[key as keyof typeof table] : (messages.uz[key] ?? key);
      return interpolate(value, vars);
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within an I18nProvider");
  return ctx;
}
